import { randomBytes } from 'node:crypto';
import type { DataSource } from 'typeorm';
import { createDataSource, dataSource } from '../src/database/data-source.js';

const scratchName = `habilitapp_schema_${randomBytes(4).toString('hex')}`;

type Row = Record<string, string>;

describe('database schema (e2e)', () => {
  let scratch: DataSource;

  const columnsOf = async (table: string): Promise<string[]> => {
    const rows: Row[] = await scratch.query(
      'SELECT column_name FROM information_schema.columns WHERE table_schema = $1 AND table_name = $2',
      ['public', table],
    );
    return rows.map((row) => row.column_name).sort();
  };

  const tablesPresent = async (): Promise<string[]> => {
    const rows: Row[] = await scratch.query(
      `SELECT table_name FROM information_schema.tables
       WHERE table_schema = 'public' AND table_name IN ('issuer', 'worker', 'certificate')`,
    );
    return rows.map((row) => row.table_name).sort();
  };

  const insertIssuer = async (
    overrides: { nit?: string; type?: string; certificateTypes?: string } = {},
  ): Promise<string> => {
    const rows: Row[] = await scratch.query(
      `INSERT INTO issuer (name, type, city, nit, ministry_registration, contact_name, email, phone, certificate_types)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9::varchar[]) RETURNING id`,
      [
        'Centro de pruebas',
        overrides.type ?? 'clinic',
        'Medellín',
        overrides.nit ?? '900000001-1',
        'REG-0001',
        'Contacto de prueba',
        'contacto@example.com',
        '3000000000',
        overrides.certificateTypes ?? '{height-work}',
      ],
    );
    return rows[0].id;
  };

  const insertWorker = async (issuerId: string, documentNumber: string, documentType = 'cc'): Promise<string> => {
    const rows: Row[] = await scratch.query(
      `INSERT INTO worker (issuer_id, full_name, document_type, document_number, consented_at)
       VALUES ($1, 'Trabajador de prueba', $2, $3, now()) RETURNING id`,
      [issuerId, documentType, documentNumber],
    );
    return rows[0].id;
  };

  const insertCertificate = async (issuerId: string, workerId: string, type = 'height-work'): Promise<number> => {
    const rows: { number: number }[] = await scratch.query(
      `INSERT INTO certificate (issuer_id, worker_id, type, issued_at, valid_until, salt, fingerprint)
       VALUES ($1, $2, $3, '2026-01-01', '2027-01-01', 'salt-test', 'fingerprint-test') RETURNING number`,
      [issuerId, workerId, type],
    );
    return rows[0].number;
  };

  beforeAll(async () => {
    await dataSource.initialize();
    await dataSource.query(`CREATE DATABASE "${scratchName}"`);
    const url = new URL(process.env.DATABASE_URL as string);
    url.pathname = `/${scratchName}`;
    scratch = createDataSource(url.toString(), process.env.DATABASE_SSL === 'true');
    await scratch.initialize();
    await scratch.runMigrations();
  }, 60_000);

  afterAll(async () => {
    if (scratch?.isInitialized) {
      await scratch.destroy();
    }
    await dataSource.query(`DROP DATABASE IF EXISTS "${scratchName}" WITH (FORCE)`);
    await dataSource.destroy();
  }, 60_000);

  it('creates the issuer, worker and certificate tables', async () => {
    expect(await tablesPresent()).toEqual(['certificate', 'issuer', 'worker']);
  });

  it('gives issuer the columns of the spec', async () => {
    expect(await columnsOf('issuer')).toEqual(
      [
        'id', 'name', 'type', 'city', 'nit', 'ministry_registration', 'contact_name', 'email', 'phone',
        'certificate_types', 'revoked_at', 'created_at', 'updated_at', 'deleted_at',
      ].sort(),
    );
  });

  it('gives worker the columns of the spec', async () => {
    expect(await columnsOf('worker')).toEqual(
      [
        'id', 'issuer_id', 'full_name', 'document_type', 'document_number', 'consented_at',
        'created_at', 'updated_at', 'deleted_at',
      ].sort(),
    );
  });

  it('gives certificate the columns of the spec', async () => {
    expect(await columnsOf('certificate')).toEqual(
      [
        'id', 'number', 'issuer_id', 'worker_id', 'type', 'issued_at', 'valid_until', 'annulled_at',
        'salt', 'fingerprint', 'created_at', 'updated_at', 'deleted_at',
      ].sort(),
    );
  });

  it('uses uuid ids generated by the database and a sequence for the certificate number', async () => {
    const rows: Row[] = await scratch.query(
      `SELECT table_name, column_name, data_type, column_default FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name IN ('issuer', 'worker', 'certificate')
         AND column_name IN ('id', 'number')`,
    );
    const ids = rows.filter((row) => row.column_name === 'id');
    const number = rows.find((row) => row.column_name === 'number');

    expect(ids).toHaveLength(3);
    for (const id of ids) {
      expect(id.data_type).toBe('uuid');
      expect(id.column_default).toContain('gen_random_uuid');
    }
    expect(number?.data_type).toBe('integer');
    expect(number?.column_default).toContain('nextval');
  });

  it('stores dates as date and moments as timestamptz', async () => {
    const rows: Row[] = await scratch.query(
      `SELECT table_name, column_name, data_type FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name IN ('issuer', 'worker', 'certificate')
         AND column_name IN ('issued_at', 'valid_until', 'revoked_at', 'annulled_at', 'consented_at', 'deleted_at')`,
    );
    const typeOf = (table: string, column: string): string | undefined =>
      rows.find((row) => row.table_name === table && row.column_name === column)?.data_type;

    expect(typeOf('certificate', 'issued_at')).toBe('date');
    expect(typeOf('certificate', 'valid_until')).toBe('date');
    expect(typeOf('certificate', 'annulled_at')).toBe('timestamp with time zone');
    expect(typeOf('issuer', 'revoked_at')).toBe('timestamp with time zone');
    expect(typeOf('worker', 'consented_at')).toBe('timestamp with time zone');
    expect(typeOf('issuer', 'deleted_at')).toBe('timestamp with time zone');
  });

  it('creates the indexes of the spec', async () => {
    const rows: Row[] = await scratch.query("SELECT indexname FROM pg_indexes WHERE schemaname = 'public'");

    expect(rows.map((row) => row.indexname)).toEqual(
      expect.arrayContaining([
        'uq_issuer_nit',
        'uq_worker_issuer_document',
        'ix_worker_issuer_id',
        'ix_certificate_issuer_id',
        'ix_certificate_worker_id',
        'ix_certificate_fingerprint',
        'uq_certificate_number',
      ]),
    );
  });

  it('rejects values outside the closed lists', async () => {
    await expect(insertIssuer({ nit: '900000002-1', type: 'hospital' })).rejects.toThrow(/ck_issuer_type/);
    await expect(insertIssuer({ nit: '900000003-1', certificateTypes: '{height-work,unknown-type}' })).rejects.toThrow(
      /ck_issuer_certificate_types/,
    );

    const issuerId = await insertIssuer({ nit: '900000004-1' });
    await expect(insertWorker(issuerId, '1000000001', 'dni')).rejects.toThrow(/ck_worker_document_type/);

    const workerId = await insertWorker(issuerId, '1000000002');
    await expect(insertCertificate(issuerId, workerId, 'diving')).rejects.toThrow(/ck_certificate_type/);
  });

  it('lets a soft-deleted issuer free its NIT but not two active ones share it', async () => {
    const first = await insertIssuer({ nit: '900000010-1' });

    await expect(insertIssuer({ nit: '900000010-1' })).rejects.toThrow(/uq_issuer_nit/);

    await scratch.query('UPDATE issuer SET deleted_at = now() WHERE id = $1', [first]);

    await expect(insertIssuer({ nit: '900000010-1' })).resolves.toEqual(expect.any(String));
  });

  it('keeps a worker document unique inside an issuer, not across issuers, and frees it on soft delete', async () => {
    const issuerA = await insertIssuer({ nit: '900000020-1' });
    const issuerB = await insertIssuer({ nit: '900000021-1' });
    const first = await insertWorker(issuerA, '1000000020');

    await expect(insertWorker(issuerA, '1000000020')).rejects.toThrow(/uq_worker_issuer_document/);
    await expect(insertWorker(issuerB, '1000000020')).resolves.toEqual(expect.any(String));

    await scratch.query('UPDATE worker SET deleted_at = now() WHERE id = $1', [first]);

    await expect(insertWorker(issuerA, '1000000020')).resolves.toEqual(expect.any(String));
  });

  it('refuses to delete an issuer that still has workers', async () => {
    const issuerId = await insertIssuer({ nit: '900000030-1' });
    await insertWorker(issuerId, '1000000030');

    await expect(scratch.query('DELETE FROM issuer WHERE id = $1', [issuerId])).rejects.toThrow(
      /foreign key constraint/,
    );
  });

  it('numbers certificates with an increasing sequence', async () => {
    const issuerId = await insertIssuer({ nit: '900000040-1' });
    const workerId = await insertWorker(issuerId, '1000000040');

    const first = await insertCertificate(issuerId, workerId);
    const second = await insertCertificate(issuerId, workerId);

    expect(second).toBeGreaterThan(first);
  });

  it('reverts and reapplies the migration cleanly', async () => {
    await scratch.undoLastMigration();
    expect(await tablesPresent()).toEqual([]);

    await scratch.runMigrations();
    expect(await tablesPresent()).toEqual(['certificate', 'issuer', 'worker']);
  });
});
